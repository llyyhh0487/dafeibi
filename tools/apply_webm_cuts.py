def main():
    with io.open(SRC, encoding="utf-8") as f:
        d = json.load(f)

    for k, v in NEW.items():
        segs = v["segments"]
        # 越界自检
        assert all(0 <= a < b <= v["duration"] + 1e-6 for a, b in segs), k + " 有越界段"
        d[k] = {
            "file": v["file"],
            "duration": v["duration"],
            "marks": [s[0] for s in segs[1:]],
            "segments": segs,
        }

    with io.open(SRC, "w", encoding="utf-8", newline="\n") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)

    total = 0
    for k in ("bibi", "jubi", "wow"):
        segs = d[k]["segments"]
        lens = sorted(b - a for a, b in segs)
        total += len(segs)
        print("  %-5s %2d 句  时长 %.2fs  中位 %.2fs  最短 %.2fs  最长 %.2fs"
              % (k, len(segs), d[k]["duration"], lens[len(lens) // 2], lens[0], lens[-1]))
    print("  合计 %d 句" % total)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
